// Runs the wavetable-oscillator-processor of the pinned superdough (packages/superdough/worklets.mjs) in Node, with the audio-worklet globals mocked,
// and writes what it computes as a Kotlin file of test vectors (hash32, noise, brownian, every warp mode on a grid, and rendered blocks):
//
//   node tools/strudel-ref/wavetable-oracle.mjs > engine/src/test/kotlin/cosic/audio/sources/WavetableOracleVectors.kt
//
// STRUDEL_DIR (default tools/strudel-ref/strudel next to this file) is the checkout made by fetch.sh. Used by WarpModesTest and WavetableOscillatorTest.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { prelude } from './worklet-sources.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.env.STRUDEL_DIR ?? path.join(here, 'strudel');
const lines = fs.readFileSync(path.join(root, 'packages/superdough/worklets.mjs'), 'utf8').split('\n');
const find = (pred, from = 0) => {
  const i = lines.findIndex((l, j) => j >= from && pred(l));
  if (i < 0) throw new Error('marker not found: ' + pred);
  return i;
};
const slice = (a, b) => lines.slice(a, b + 1).join('\n');

const SR = 48000;
globalThis.sampleRate = SR;
globalThis.currentTime = 0;
globalThis.AudioWorkletProcessor = class {
  constructor() {
    this.port = {};
  }
};
const registry = {};
globalThis.registerProcessor = (n, c) => {
  registry[n] = c;
};

const detunerStart = find((l) => l.startsWith('// Optimized per-voice detuner'));
const detunerEnd = find((l) => l.startsWith('// Smooth waveshape')) - 1;
const wtStart = find((l) => l.startsWith('export const WarpMode'));
const wtEnd = find((l) => l.includes("registerProcessor('wavetable-oscillator-processor'"));
const code =
  prelude + '\n' + slice(detunerStart, detunerEnd) + '\n' + slice(wtStart, wtEnd).replace('export const WarpMode', 'const WarpMode') +
  '\nglobalThis.__wt = { hash32, hash01, noise, brownian, bitReverse, WarpMode };';
(0, eval)(code);
const { hash32, hash01, noise, brownian } = globalThis.__wt;
const Processor = registry['wavetable-oscillator-processor'];

const num = (x) => (Object.is(x, -0) ? '-0.0' : Number.isInteger(x) && Math.abs(x) < 1e15 ? x.toFixed(1) : String(x).replace(/e\+?/, 'e'));
const dl = (xs) => `doubleArrayOf(${[...xs].map(num).join(', ')})`;

const out = [];
out.push('package cosic.audio.sources', '');
out.push('// Generated by tools/strudel-ref/wavetable-oracle.mjs from the wavetable-oscillator-processor of superdough (pinned commit). Do not edit.', '');
out.push('internal object WavetableOracleVectors {');

const hashIn = [0, 1, 2, 3, 7, 100, 255, 12345, 65535, -1, -7];
out.push(`    val hashInputs = intArrayOf(${hashIn.join(', ')})`);
out.push(`    val hash32 = longArrayOf(${hashIn.map((i) => hash32(i)).join('L, ')}L)`);
out.push(`    val hash01 = ${dl(hashIn.map(hash01))}`);
const noiseIn = [0, 0.25, 0.5, 1.75, 3.1, 17.9, 63.99, 255.5];
out.push(`    val noiseInputs = ${dl(noiseIn)}`);
out.push(`    val noise = ${dl(noiseIn.map(noise))}`);
out.push(`    val brownian = ${dl(noiseIn.map((x) => brownian(x, 4)))}`);

// every warp mode (and a non-mode) on a grid; the processor's own _warpPhase
const warpProc = new Processor({});
const modes = Array.from({ length: 24 }, (_, i) => i).concat([2.5, -1]);
const amounts = [0, 0.25, 0.5, 0.75, 1];
const phases = [0, 0.1, 0.2525, 0.5, 0.7525, 0.9, 0.999];
const warp = [];
for (const m of modes) for (const a of amounts) for (const p of phases) warp.push(warpProc._warpPhase(p, a, m));
out.push(`    val warpModes = ${dl(modes)}`);
out.push(`    val warpAmounts = ${dl(amounts)}`);
out.push(`    val warpPhases = ${dl(phases)}`);
out.push(`    val warp = ${dl(warp)}`);

// rendered blocks: a table of 3 frames of 8 values, 3 quanta
const frames = [
  [0, 0.5, 1, 0.5, 0, -0.5, -1, -0.5],
  [0.1, 0.9, -0.3, 0.7, -0.8, 0.2, 0.4, -0.6],
  [1, -1, 1, -1, 0.5, -0.5, 0.25, -0.25],
].map((f) => Float32Array.from(f));
const cases = [
  ['single', { frequency: 440, detune: 0, freqspread: 0.18, position: 0.4, warp: 0.3, warpMode: 8, voices: 1, panspread: 0.7, phaserand: 0 }],
  ['unison', { frequency: 220, detune: 0, freqspread: 0.18, position: 0.75, warp: 0.6, warpMode: 5, voices: 3, panspread: 0.7, phaserand: 0 }],
  ['flip', { frequency: 330, detune: 0, freqspread: 0.3, position: 1, warp: 0.5, warpMode: 21, voices: 2, panspread: 0.2, phaserand: 0 }],
  ['detuned', { frequency: 110, detune: 37, freqspread: 0.5, position: 0.1, warp: 0.9, warpMode: 14, voices: 4, panspread: 1, phaserand: 0 }],
];
out.push('    /** name, then the left and the right channel of 3 render quanta of 128 frames at 48000 Hz, of a table of [tableFrames]. */');
out.push('    val tableFrames = listOf(' + frames.map((f) => `floatArrayOf(${[...f].map((x) => num(x) + 'f').join(', ')})`).join(', ') + ')');
out.push('    class Block(val name: String, val frequency: Double, val detune: Double, val freqspread: Double, val position: Double, val warp: Double, val warpMode: Double, val voices: Double, val panspread: Double, val left: DoubleArray, val right: DoubleArray)');
const blocks = [];
for (const [name, params] of cases) {
  const proc = new Processor({});
  proc.initialize({ key: name, frames, frameLen: 8 });
  const L = new Float32Array(384);
  const R = new Float32Array(384);
  const p = Object.fromEntries(Object.entries({ begin: 0, end: 100, ...params }).map(([k, v]) => [k, [v]]));
  for (let q = 0; q < 3; q++) {
    globalThis.currentTime = ((q + 1) * 128) / SR;
    const l = new Float32Array(128);
    const r = new Float32Array(128);
    proc.process([], [[l, r]], p);
    L.set(l, q * 128);
    R.set(r, q * 128);
  }
  blocks.push(
    `        Block("${name}", ${num(params.frequency)}, ${num(params.detune)}, ${num(params.freqspread)}, ${num(params.position)}, ${num(params.warp)}, ${num(params.warpMode)}, ${num(params.voices)}, ${num(params.panspread)},\n            ${dl(L)},\n            ${dl(R)}),`,
  );
}
out.push('    val blocks = listOf(', ...blocks, '    )');
out.push('}');
console.log(out.join('\n'));
