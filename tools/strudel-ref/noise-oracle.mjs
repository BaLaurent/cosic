// Runs getNoiseBuffer of the pinned superdough (packages/superdough/noise.mjs, sliced out of the file and evaluated as it is) in Node with Math.random
// replaced by SplitMix64 (the generator of SourceRng) and writes a checksum and sample points of each buffer as a Kotlin file of test vectors:
//
//   node tools/strudel-ref/noise-oracle.mjs > engine/src/test/kotlin/cosic/audio/sources/NoiseOracleVectors.kt
//
// STRUDEL_DIR (default tools/strudel-ref/strudel next to this file) is the checkout made by fetch.sh. Used by NoiseBuffersTest, which builds the same
// buffers with NoiseBuffers.generate and compares them bit for bit (the checksum covers every float32 of the buffer).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.env.STRUDEL_DIR ?? path.join(here, 'strudel');
const source = fs.readFileSync(path.join(root, 'packages/superdough/noise.mjs'), 'utf8');
const start = source.indexOf('let noiseCache = {};');
const end = source.indexOf('// expects one of noises as type');
if (start < 0 || end < 0) throw new Error('noise.mjs does not look like the pinned one');
const code = source.slice(start, end).replace('export function getNoiseBuffer', 'function getNoiseBuffer');

const MASK = (1n << 64n) - 1n;
function splitMix64(seed) {
  let state = BigInt.asUintN(64, BigInt(seed));
  return () => {
    state = (state + 0x9e3779b97f4a7c15n) & MASK;
    let z = state;
    z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & MASK;
    z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & MASK;
    z = z ^ (z >> 31n);
    return Number(z >> 11n) * 2 ** -53;
  };
}

/** The real getNoiseBuffer with a fresh cache, a seeded Math.random and a mock AudioContext whose buffers are Float32Arrays. */
function buffer(type, sampleRate, density, seed) {
  const random = splitMix64(seed);
  const MathMock = Object.create(Math);
  MathMock.random = random;
  const context = {
    sampleRate,
    createBuffer: (channels, length) => {
      const data = new Float32Array(length);
      return { getChannelData: () => data };
    },
  };
  const getNoiseBuffer = new Function('getAudioContext', 'Math', 'drywet', 'onceEnded', 'releaseAudioNode', `${code}\nreturn getNoiseBuffer;`)(() => context, MathMock);
  return getNoiseBuffer(type, density).getChannelData(0);
}

/** A 32-bit FNV-1a over the float32 bit patterns, word by word: the same loop as in NoiseBuffersTest. */
function checksum(data) {
  const words = new Uint32Array(data.buffer, data.byteOffset, data.length);
  let h = 2166136261;
  for (const w of words) h = Math.imul(h ^ w, 16777619);
  return h | 0;
}

const cases = [
  ['WHITE', 'white', 48000, 0.02, 7],
  ['PINK', 'pink', 48000, 0.02, 7],
  ['BROWN', 'brown', 48000, 0.02, 7],
  ['CRACKLE', 'crackle', 48000, 2, 7],
  ['CRACKLE', 'crackle', 48000, 0.5, 1234567],
  ['WHITE', 'white', 44100, 0.02, -5],
  ['PINK', 'pink', 44100, 0.02, 99],
  ['BROWN', 'brown', 22050, 0.02, 3],
];

