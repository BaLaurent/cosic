// Reference data for the mini-notation package of the script engine (engine/src/test/kotlin/cosic/mini/MiniOracleTest.kt).
//
// It runs mini-notation strings through Strudel's own @strudel/mini (packages/mini at the pinned commit: the Peggy
// parser krill-parser.js and mini.mjs) and stores what came out, so the Kotlin parser and patternifier can be compared
// with it case by case, hap by hap, offset by offset, error message by error message:
//
//   node tools/strudel-ref/mini-oracle.mjs                 writes engine/src/test/resources/mini/oracle.json
//   node tools/strudel-ref/mini-oracle.mjs --letters       writes engine/src/main/kotlin/cosic/mini/MiniLetters.kt
//   node tools/strudel-ref/mini-oracle.mjs --show '<src>'  prints what Strudel makes of one string
//   node tools/strudel-ref/mini-oracle.mjs --strings <in.json> <out.json>   the same for the strings of a JSON array (a corpus
//                                                          of your own: COSIC_MINI_ORACLE=<out.json> ./gradlew :engine:test --rerun --tests 'cosic.mini.MiniOracleTest')
//
// Every case is `m(src, 10)`, the call the transpiler writes for the double-quoted string `"src"` that starts at offset 10.
// What is stored per case:
//   src      the mini-notation, without its quotes
//   begin    the cycle the query starts at: it is negative, so that the time before cycle 0 is compared too
//   cycles   the number of cycles that were queried, from `begin`
//   haps     the haps of the cycles in order, `hap.show(true)` (the strings of the snapshot tests)
//   locs     for each hap the source ranges of its context, sorted
//   steps    the number of steps per cycle (`pattern._steps`), if it has any
//   leaves   `getLeafLocations('"src"', 10)`: the ranges of the atoms in the order Strudel visits them
//   error    the message of the error that evaluating the string gave, instead of all of the above
//
// The random cases come from a generator with a fixed seed, so running this again leaves `git status` clean.
