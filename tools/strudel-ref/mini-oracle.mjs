// ---- the letters of the grammar ---------------------------------------------------------------------------------------

/** The `step_char` class of the generated parser (`peg$r6`), as the list of its code unit ranges. */
function stepCharRanges() {
  const text = fs.readFileSync(path.join(strudel, 'packages/mini/krill-parser.js'), 'utf8');
  const match = /var peg\$r6 = \/(\^\[.*\])\/;/.exec(text);
  if (!match) throw new Error('peg$r6 not found in krill-parser.js');
  const regex = new RegExp(match[1]);
  const ranges = [];
  let from = -1;
  for (let c = 0; c <= 0x10000; c++) {
    const inside = c <= 0xffff && regex.test(String.fromCharCode(c));
    if (inside && from < 0) from = c;
    if (!inside && from >= 0) {
      ranges.push([from, c - 1]);
      from = -1;
    }
  }
  return ranges;
}

function writeLetters() {
  const ranges = stepCharRanges();
  const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
  const lines = [];
  for (let i = 0; i < ranges.length; i += 6) {
    lines.push('        ' + ranges.slice(i, i + 6).map(([a, b]) => `${hex(a)}, ${hex(b)}`).join(', ') + ',');
  }
  const out = `package cosic.mini

/*
 * Generated by tools/strudel-ref/mini-oracle.mjs --letters from the \`step_char\` class of Strudel's generated mini-notation
 * parser (packages/mini/krill-parser.js, \`peg$r6\`): \`unicode_letter / [0-9~] / "-" / "#" / "." / "^" / "_"\` of krill.pegjs.
 * The Unicode tables of that grammar are older than the JVM's, so Character.getType is not used (MiniLettersTest compares
 * the two and reports where they differ). Do not edit by hand.
 */
internal object MiniLetters {
    /** Pairs of the first and the last UTF-16 code unit of each range, ascending. */
    private val RANGES = intArrayOf(
${lines.join('\n')}
    )

    /** Whether [c] may be part of an atom: a letter of the grammar's tables, a digit, or one of \`~ - # . ^ _\`. */
    fun isStepChar(c: Char): Boolean {
        val code = c.code
        var lo = 0
        var hi = RANGES.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            when {
                code < RANGES[2 * mid] -> hi = mid - 1
                code > RANGES[2 * mid + 1] -> lo = mid + 1
                else -> return true
            }
        }
        return false
    }
}
`;
  fs.writeFileSync(path.join(root, 'engine/src/main/kotlin/cosic/mini/MiniLetters.kt'), out);
  console.log(`MiniLetters.kt: ${ranges.length} ranges`);
}

// ---- running a string ---------------------------------------------------------------------------------------------

const MAX_HAPS = 100;

function runCase(src, wantedCycles = 4) {
  const [l, e] = [console.log, console.error];
  console.log = console.error = () => {};
  try {
    return runCaseQuietly(src, wantedCycles);
  } finally {
    console.log = l;
    console.error = e;
  }
}

function runCaseQuietly(src, wantedCycles) {
  const result = { src };
  let pat;
  try {
    pat = mini.m(src, OFFSET);
  } catch (e) {
    result.error = String(e.message);
    return result;
  }
  let cycles = wantedCycles;
  let haps;
  try {
    haps = pat.sortHapsByPart().queryArc(BEGIN, BEGIN + cycles);
    if (haps.length > MAX_HAPS) {
      cycles = 1;
      haps = pat.sortHapsByPart().queryArc(BEGIN, BEGIN + cycles);
    }
  } catch (e) {
    result.error = String(e.message);
    return result;
  }
  if (haps.length > MAX_HAPS) return null;
  result.begin = BEGIN;
  result.cycles = cycles;
  result.haps = haps.map((h) => h.show(true));
  result.locs = haps.map((h) =>
    (h.context.locations ?? []).map((l) => [l.start, l.end]).sort((a, b) => a[0] - b[0] || a[1] - b[1]),
  );
  result.steps = pat._steps === undefined ? null : pat._steps.show();
  try {
    result.leaves = mini.getLeafLocations(`"${src}"`, OFFSET);
  } catch (e) {
    result.leavesError = String(e.message);
  }
  return result;
}

