// ---- a generator of strings ---------------------------------------------------------------------------------------

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function generate(seed, count) {
  const rnd = mulberry32(seed);
  const pick = (xs) => xs[Math.floor(rnd() * xs.length)];
  const chance = (p) => rnd() < p;
  const ATOMS = ['a', 'b', 'c', 'd', 'bd', 'sd', 'hh', 'cp', 'x', 'c3', 'e4', 'bb2', 'f#3', '0', '1', '2', '3', '4', '8', '12', '0.5', '1.5', '-1', '1e1', '0x10', '~', '~', '-', 'a.b', 'a_b', '^x', 'é', 'Ω', 'e', '5e'];
  const NUMS = ['2', '3', '4', '0.5', '1.5', '8', '0', '1', '16'];
  const sp = () => pick([' ', ' ', ' ', ' ', '  ', '\n ', '\t']);

  const slice = (depth) => {
    const roll = rnd();
    if (depth <= 0 || roll < 0.55) return pick(ATOMS);
    if (roll < 0.7) return '[' + stackOrChoose(depth - 1) + ']';
    if (roll < 0.82) return '<' + polymeterStack(depth - 1) + '>';
    const spc = chance(0.4) ? '%' + (chance(0.6) ? pick(NUMS) : chance(0.5) ? '<2 3>' : '[2 4]') : '';
    return '{' + polymeterStack(depth - 1) + '}' + spc;
  };
  const arg = (depth) => (chance(0.6) ? pick(NUMS) : chance(0.5) ? '<' + pick(NUMS) + sp() + pick(NUMS) + '>' : '[' + pick(NUMS) + sp() + pick(NUMS) + ']');
  const op = (depth) => {
    const roll = rnd();
    if (roll < 0.2) return '*' + arg(depth);
    if (roll < 0.3) return '/' + arg(depth);
    if (roll < 0.38) return '!' + (chance(0.5) ? pick(['2', '3', '4']) : '');
    if (roll < 0.46) return '@' + pick(['2', '3', '1.5', '0', '']);
    if (roll < 0.52) return sp() + '_' + pick(['', '', '2']);
    if (roll < 0.62) return '?' + (chance(0.4) ? pick(['0.2', '0.8', '0.5']) : '');
    if (roll < 0.72) return '(' + pick(['3', '5', '2', '1', '7', '-3', '<3 5>', '3 5']) + ',' + pick(['8', '8', '5', '16', '-8', '4', '<8 16>']) + (chance(0.4) ? ',' + pick(['0', '1', '2', '<0 2>']) : '') + ')';
    if (roll < 0.82) return ':' + pick(['3', 'x', '[b c]', '<b c>', 'd']);
    if (roll < 0.9) return sp() + '..' + sp() + pick(['3', '4', '<2 4>', '1']);
    return '!';
  };
  const element = (depth) => {
    let s = slice(depth);
    const n = chance(0.5) ? 0 : chance(0.6) ? 1 : 2;
    for (let i = 0; i < n; i++) s += op(depth);
    return s;
  };
  const sequence = (depth) => {
    const n = 1 + Math.floor(rnd() * 4);
    let s = chance(0.05) ? '^' : '';
    for (let i = 0; i < n; i++) s += (i ? sp() : '') + element(depth);
    return s;
  };
  const polymeterStack = (depth) => {
    const n = chance(0.7) ? 1 : 2;
    return Array.from({ length: n }, () => sequence(depth)).join(chance(0.5) ? ', ' : ',');
  };
  const stackOrChoose = (depth) => {
    const roll = rnd();
    const n = roll < 0.6 ? 1 : 2 + Math.floor(rnd() * 2);
    const sep = roll < 0.8 ? ', ' : roll < 0.9 ? ' | ' : ' . ';
    return Array.from({ length: n }, () => sequence(depth)).join(sep);
  };
  const mutate = (s) => {
    const chars = '[]{}<>(),|.*/!@?:%^~"\' _-#a1';
    const i = Math.floor(rnd() * (s.length + 1));
    if (chance(0.5) && s.length > 0) return s.slice(0, i) + s.slice(i + 1);
    return s.slice(0, i) + pick(chars.split('')) + s.slice(i);
  };

  const out = [];
  for (let i = 0; i < count; i++) {
    let s = stackOrChoose(1 + Math.floor(rnd() * 3));
    if (chance(0.12)) s = mutate(s);
    out.push(s);
  }
  return out;
}

// ---- main ---------------------------------------------------------------------------------------------------------

function main() {
  const args = process.argv.slice(2);
  if (args[0] === '--letters') return writeLetters();
  if (args[0] === '--strings') {
    const strings = JSON.parse(fs.readFileSync(args[1], 'utf8'));
    const cases = [...new Set(strings)].map((src) => runCase(src)).filter(Boolean);
    fs.writeFileSync(args[2], `[\n${cases.map((c) => JSON.stringify(c)).join(',\n')}\n]\n`);
    console.log(`mini oracle: ${cases.length} cases (${cases.filter((c) => c.error).length} errors) written to ${args[2]}`);
    return;
  }
  if (args[0] === '--show') {
    console.log(JSON.stringify(runCase(args[1]), null, 1));
    return;
  }
  const sources = [...handwritten, ...withBreaks, ...generate(20241120, 700)];
  const seen = new Set();
  const cases = [];
  for (const src of sources) {
    if (seen.has(src)) continue;
    seen.add(src);
    const c = runCase(src);
    if (c) cases.push(c);
  }
  const dir = path.join(root, 'engine/src/test/resources/mini');
  fs.mkdirSync(dir, { recursive: true });
  const text = `[\n${cases.map((c) => JSON.stringify(c)).join(',\n')}\n]\n`;
  fs.writeFileSync(path.join(dir, 'oracle.json'), text);
  const errors = cases.filter((c) => c.error).length;
  console.log(`mini oracle: ${cases.length} cases (${errors} errors), ${(text.length / 1024).toFixed(0)} KiB`);
}

main();
