// The data tables of the tonal functions of the engine (engine/src/main/kotlin/cosic/pattern/{Tonal,Voicings}.kt), read from
// what the pinned checkout really holds, so nothing is typed in by hand:
//
//   node tools/strudel-ref/tonal-data.mjs
//
// Output (engine/src/main/resources/cosic/tonal/):
//   scale-types.txt           the scale types of @tonaljs/scale-type (data.ts), in order: `name|alias|alias<TAB>intervals`
//   ireal.txt                 `[simple]` and `[complex]`, the voicing dictionaries of packages/tonal/ireal.mjs as written in the
//                             file (before the aliases voicings.mjs adds): `symbol<TAB>voicing|voicing`, symbols in JavaScript key order
//   voicing-dictionaries.txt  `[lefthand]`, `[guidetones]`, `[triads]` and `[legacy]` of packages/tonal/voicings.mjs, same format
// and, for the tests that check the Kotlin port of what happens at load time:
//   engine/src/test/resources/tonal/load-state.json
//                             the scale types with the setNum and chroma tonal computes, the keys of ScaleType's index, and the
//                             symbols of the registry's dictionaries once voicings.mjs has added its aliases
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.env.COSIC_ROOT ?? path.resolve(here, '../..');
const tonalDir = path.join(here, 'strudel/packages/tonal');
const resources = path.join(root, 'engine/src/main/resources/cosic/tonal');
const testResources = path.join(root, 'engine/src/test/resources/tonal');

const importFile = (file) => import(pathToFileURL(file).href);
const tonalLib = await importFile(path.join(tonalDir, 'node_modules/@tonaljs/tonal/dist/index.mjs'));
const { ScaleType } = tonalLib;
const ireal = await importFile(path.join(tonalDir, 'ireal.mjs'));
// the exports of voicings.mjs are what the oracle's globals are; it adds the aliases to the ireal dictionaries when it loads
const rawIreal = {
  simple: structuredClone(ireal.simple),
  complex: structuredClone(ireal.complex),
};
const voicings = await importFile(path.join(tonalDir, 'voicings.mjs'));

// ---- scale types -----------------------------------------------------------------------------------------------------

const scaleTypes = ScaleType.all();
const scaleLines = scaleTypes.map((s) => `${[s.name, ...s.aliases].join('|')}\t${s.intervals.join(' ')}`);
for (const line of scaleLines) {
  if (line.split('\t').length !== 2 || /[\r\n]/.test(line)) throw new Error(`cannot write ${JSON.stringify(line)}`);
}

// ---- voicing dictionaries -----------------------------------------------------------------------------------------------

const section = (title, dictionary) => {
  const lines = [`[${title}]`];
  for (const symbol of Object.keys(dictionary)) {
    const entry = dictionary[symbol];
    if (!Array.isArray(entry) || !entry.every((v) => typeof v === 'string')) {
      throw new Error(`${title}.${symbol}: expected an array of strings`);
    }
    if (/[\t|\r\n]/.test(symbol) || entry.some((v) => /[\t|\r\n]/.test(v))) throw new Error(`${title}.${symbol}: cannot be written`);
    lines.push(`${symbol}\t${entry.join('|')}`);
  }
  return lines;
};

const registry = voicings.voicingRegistry;
const iRealLines = [...section('simple', rawIreal.simple), ...section('complex', rawIreal.complex)];
const dictionaryLines = ['lefthand', 'guidetones', 'triads', 'legacy'].flatMap((name) => section(name, registry[name].dictionary));

const header = (what) => `# ${what}; generated by the tonal-data script of the repository, do not edit`;
fs.mkdirSync(resources, { recursive: true });
fs.writeFileSync(
  path.join(resources, 'scale-types.txt'),
  [header('the scale types of @tonaljs/scale-type 4.9.1 (name|aliases, tab, intervals)'), ...scaleLines, ''].join('\n'),
);
fs.writeFileSync(
  path.join(resources, 'ireal.txt'),
  [header('packages/tonal/ireal.mjs (symbol, tab, voicings separated by |)'), ...iRealLines, ''].join('\n'),
);
fs.writeFileSync(
  path.join(resources, 'voicing-dictionaries.txt'),
  [header('the dictionaries of packages/tonal/voicings.mjs (symbol, tab, voicings separated by |)'), ...dictionaryLines, ''].join('\n'),
);

// ---- what the tests compare the port with -----------------------------------------------------------------------------

const loadState = {
  scaleTypes: scaleTypes.map((s) => ({
    name: s.name,
    aliases: s.aliases,
    intervals: s.intervals,
    setNum: s.setNum,
    chroma: s.chroma,
    normalized: s.normalized,
  })),
  scaleTypeKeys: ScaleType.keys(),
  registry: Object.fromEntries(Object.entries(registry).map(([name, entry]) => [name, {
    symbols: Object.keys(entry.dictionary),
    range: entry.range ?? null,
    mode: entry.mode ?? null,
    anchor: entry.anchor ?? null,
  }])),
  iRealAliased: {
    simple: Object.fromEntries(Object.keys(ireal.simple).map((symbol) => [symbol, ireal.simple[symbol]])),
    complex: Object.fromEntries(Object.keys(ireal.complex).map((symbol) => [symbol, ireal.complex[symbol]])),
  },
};
fs.mkdirSync(testResources, { recursive: true });
fs.writeFileSync(path.join(testResources, 'load-state.json'), JSON.stringify(loadState, null, 1) + '\n');

console.log(
  `scale types ${scaleTypes.length}, index keys ${loadState.scaleTypeKeys.length}, ` +
    `ireal ${Object.keys(rawIreal.simple).length}+${Object.keys(rawIreal.complex).length} symbols ` +
    `(${Object.keys(ireal.simple).length} with aliases), registry ${Object.keys(registry).join(' ')}`,
);
